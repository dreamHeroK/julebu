const tokens = (en) => en.split(/\s+/).map((t) => t.replace(/^[^\w']+|[^\w']+$/g, '')).filter(Boolean);

function fromChunks(en, chunks, override = {}) {
  const words = [], missing = [];
  chunks.split('|').forEach((chunk, i) => {
    for (const t of tokens(chunk)) {
      const hit = override[t.toLowerCase()] || LEXICON[t.toLowerCase()];
      if (!hit) missing.push(t);
      else words.push([t, ...hit, i]);
    }
  });
  if (missing.length) throw new Error(`词典缺词「${missing.join(', ')}」：${en}`);
  if (words.map((w) => w[0]).join(' ') !== tokens(en).join(' ')) throw new Error(`语块与句子不一致：${en} ≠ ${chunks}`);
  return words;
}

/** 句子构造：words 可以是逐词数组（旧写法），也可以是用 | 分隔的语块字符串（查词典） */
export function s(en, zh, words, override) {
  if (typeof words === 'string') words = fromChunks(en, words, override);
  return {
    en,
    zh,
    w: words.map(([t, ipa, pos, cn, chunk]) => ({ t, ipa, pos, cn, chunk })),
  };
}
